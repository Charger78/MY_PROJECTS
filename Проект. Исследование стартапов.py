def clean_column_names(df):
    """
    Функция для очистки названий столбцов DataFrame:
    - удаляет пробелы в начале названий;
    - преобразует 'round_A', 'round_B' - 'round_a', 'round_b'.
    
    """
    new_columns = []
    
    for col in df.columns:
        # 1. Удаляем пробелы в начале и в конце названия
        col = col.strip()
        
        # 2. Проверяем, начинается ли название с 'round_' и содержит ли заглавную букву после
        if col.startswith('round_'):
            # Берём часть после 'round_' и приводим первую букву к нижнему регистру
            suffix = col[6:] 
            new_suffix = suffix.lower() + suffix[1:] 
            col = 'round_' + new_suffix
        
        new_columns.append(col)
    
    # Применяем новые названия к DataFrame
    df.columns = new_columns
    return df


