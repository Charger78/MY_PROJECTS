# Обработываем аномальные значения (выбросы)
def remove_outliers_iqr(series):
    Q1 = series.quantile(0.25)
    Q3 = series.quantile(0.75)
    IQR = Q3 - Q1
    lower_bound = Q1 - 1.5 * IQR
    upper_bound = Q3 + 1.5 * IQR
    return series.apply(lambda x: np.nan if x < lower_bound or x > upper_bound else x)

# Применяем функцию к каждому столбцу с return_ratio
for col in results_df.columns[1:]:  # пропускаем столбец с годами
    results_df[col] = remove_outliers_iqr(results_df[col])


