# Расчётываем IQR для каждой группы
def calculate_iqr_bounds(series):
    q1 = series.quantile(0.25)  # 25-й перцентиль
    q3 = series.quantile(0.75)  # 75-й перцентиль
    iqr = q3 - q1
    Q1 = q1 - 1.5 * iqr  # нижняя граница
    Q3 = q3 + 1.5 * iqr  # верхняя граница
    return Q1, Q3

# Группируем данные и рассчитываем границы
iqr_bounds = invest_df.groupby('market')['funding_total_usd'].apply(calculate_iqr_bounds)


# In[48]:


# Маркируем аномальные значения
def is_outlier(row, bounds_dict):
    market = row['market']
    funding = row['funding_total_usd']
    lower, upper = bounds_dict[market]
    return funding < lower or funding > upper

